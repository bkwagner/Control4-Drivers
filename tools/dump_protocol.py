#!/usr/bin/env python3
"""Extract the Android TV Remote v2 protobuf schema into project references.

The androidtvremote2 package ships only compiled _pb2 modules, but their descriptors
carry the full schema. This reads them and emits:

    docs/protocol-reference.md   - human-readable schema, for writing the Lua encoder
    driver/lib/keycodes.lua      - RemoteKeyCode / RemoteDirection as Lua tables

Regenerate after upgrading androidtvremote2:
    python tools/dump_protocol.py
"""

from __future__ import annotations

import sys
from pathlib import Path

try:
    from androidtvremote2 import remotemessage_pb2 as rm
except ImportError:
    sys.exit("error: pip install -r tools/requirements.txt")

# protobuf FieldDescriptor.type -> (readable name, wire type)
# Only these three wire encodings appear in this schema, which is why a hand-rolled
# Lua encoder is practical.
TYPES = {
    5:  ("int32",  "varint"),
    8:  ("bool",   "varint"),
    9:  ("string", "length-delimited"),
    13: ("uint32", "varint"),
}

REPO = Path(__file__).resolve().parent.parent
DOC_OUT = REPO / "docs" / "protocol-reference.md"
LUA_OUT = REPO / "driver" / "lib" / "keycodes.lua"

# Keys a media_player driver actually binds. Everything else is still emitted, but
# these get called out so the driver work has an obvious starting set.
NOTABLE = [
    "KEYCODE_DPAD_UP", "KEYCODE_DPAD_DOWN", "KEYCODE_DPAD_LEFT", "KEYCODE_DPAD_RIGHT",
    "KEYCODE_DPAD_CENTER", "KEYCODE_BACK", "KEYCODE_HOME", "KEYCODE_MENU",
    "KEYCODE_MEDIA_PLAY_PAUSE", "KEYCODE_MEDIA_PLAY", "KEYCODE_MEDIA_PAUSE",
    "KEYCODE_MEDIA_STOP", "KEYCODE_MEDIA_NEXT", "KEYCODE_MEDIA_PREVIOUS",
    "KEYCODE_MEDIA_REWIND", "KEYCODE_MEDIA_FAST_FORWARD", "KEYCODE_MEDIA_RECORD",
    "KEYCODE_VOLUME_UP", "KEYCODE_VOLUME_DOWN", "KEYCODE_VOLUME_MUTE",
    "KEYCODE_POWER", "KEYCODE_TV_POWER", "KEYCODE_INFO", "KEYCODE_GUIDE",
    "KEYCODE_CHANNEL_UP", "KEYCODE_CHANNEL_DOWN", "KEYCODE_SEARCH",
    "KEYCODE_PROG_RED", "KEYCODE_PROG_GREEN", "KEYCODE_PROG_YELLOW", "KEYCODE_PROG_BLUE",
] + [f"KEYCODE_{n}" for n in range(10)]


def field_rows(msg) -> list[tuple[str, str, str, str]]:
    rows = []
    for f in msg.fields:
        if f.message_type:
            tname, wire = f.message_type.name, "length-delimited"
        elif f.enum_type:
            tname, wire = f.enum_type.name, "varint"
        else:
            tname, wire = TYPES.get(f.type, (str(f.type), "?"))
        rows.append((str(f.number), f.name, tname, wire))
    return rows


def write_doc(fp) -> None:
    out = [
        "# Android TV Remote v2 — protobuf reference",
        "",
        "Generated by `tools/dump_protocol.py` from the descriptors compiled into",
        "`androidtvremote2`. Do not edit by hand; regenerate instead.",
        "",
        "## Framing",
        "",
        "Every message on **both** ports 6466 and 6467 is a length-delimited protobuf:",
        "a varint byte length followed by that many bytes of encoded `RemoteMessage`.",
        "TCP will fragment these, so a receiver must buffer and re-frame rather than",
        "assuming one read equals one message.",
        "",
        "## Wire types in use",
        "",
        "Only two protobuf wire types appear across the whole schema:",
        "",
        "| Wire type | Encoding | Used by |",
        "|---|---|---|",
        "| 0 | varint | `int32`, `uint32`, `bool`, all enums |",
        "| 2 | length-delimited | `string`, nested messages |",
        "",
        "That is why hand-rolling the encoder in Lua is practical — no need for a",
        "protobuf runtime, no fixed32/fixed64/zigzag handling.",
        "",
        "## RemoteMessage — the top-level envelope",
        "",
        "Exactly one field is set per message; the field number selects the type.",
        "",
        "| # | Field | Type |",
        "|---|---|---|",
    ]
    top = fp.message_types_by_name["RemoteMessage"]
    for num, name, tname, _ in field_rows(top):
        out.append(f"| {num} | `{name}` | {tname} |")

    out += ["", "## Message definitions", ""]
    for name in sorted(fp.message_types_by_name):
        if name == "RemoteMessage":
            continue
        msg = fp.message_types_by_name[name]
        out += [f"### {name}", "", "| # | Field | Type | Wire |", "|---|---|---|---|"]
        rows = field_rows(msg)
        if not rows:
            out.append("| _(empty message)_ | | | |")
        for num, fname, tname, wire in rows:
            out.append(f"| {num} | `{fname}` | {tname} | {wire} |")
        out.append("")

    direction = fp.enum_types_by_name["RemoteDirection"]
    out += ["## RemoteDirection", "", "| Value | Name |", "|---|---|"]
    for v in direction.values:
        out.append(f"| {v.number} | `{v.name}` |")

    keycodes = fp.enum_types_by_name["RemoteKeyCode"]
    out += [
        "",
        f"## RemoteKeyCode — {len(keycodes.values)} values",
        "",
        "Full table in `driver/lib/keycodes.lua`. The ones a media_player driver binds:",
        "",
        "| Value | Name |",
        "|---|---|",
    ]
    by_name = {v.name: v.number for v in keycodes.values}
    for n in NOTABLE:
        if n in by_name:
            out.append(f"| {by_name[n]} | `{n}` |")

    DOC_OUT.parent.mkdir(parents=True, exist_ok=True)
    DOC_OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {DOC_OUT.relative_to(REPO)}")


def write_lua(fp) -> None:
    keycodes = fp.enum_types_by_name["RemoteKeyCode"]
    direction = fp.enum_types_by_name["RemoteDirection"]

    out = [
        "--[[",
        "\tAndroid TV Remote v2 key codes and directions.",
        "",
        "\tGENERATED by tools/dump_protocol.py - do not edit by hand.",
        "]]",
        "",
        "local M = {}",
        "",
        "M.DIRECTION = {",
    ]
    for v in direction.values:
        out.append(f"\t{v.name} = {v.number},")
    out += ["}", "", "M.KEYCODE = {"]
    for v in sorted(keycodes.values, key=lambda v: v.number):
        out.append(f"\t{v.name} = {v.number},")
    out += [
        "}",
        "",
        "-- Reverse lookup, for logging received state.",
        "M.KEYCODE_NAME = {}",
        "for name, num in pairs(M.KEYCODE) do",
        "\tM.KEYCODE_NAME[num] = name",
        "end",
        "",
        "return M",
    ]

    LUA_OUT.parent.mkdir(parents=True, exist_ok=True)
    LUA_OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {LUA_OUT.relative_to(REPO)}  ({len(keycodes.values)} key codes)")


def main() -> None:
    fp = rm.DESCRIPTOR
    write_doc(fp)
    write_lua(fp)


if __name__ == "__main__":
    main()
